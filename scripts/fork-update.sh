#!/bin/bash
#
# Back up, then update an existing Dune Weaver install from the adman234 fork.
# Works for:
#   - a normal upstream (tuanchris) install  -> switches it to the fork
#   - an install running a fork branch (e.g. the LED random-effect branch)
#   - an install that's already on the fork  -> plain update
#
# Paste into an SSH session on the Pi (as your normal user, not root):
#
#   curl -fsSL https://raw.githubusercontent.com/adman234/dune-weaver/main/scripts/fork-update.sh | bash
#
# Environment overrides:
#   DW_BRANCH=main          branch to end up on (default: stay on the current
#                           branch if the fork has it, otherwise main)
#   DW_REPO=<git url>       repo to switch to
#   DW_DIR=<path>           install location (default: auto-detect)
#   DW_BACKUP_ONLY=1        make the backup and stop
#
# Backups go to ~/dw-backups/<date-time>/ with a RESTORE.txt inside.

main() {
    set -euo pipefail

    local repo="${DW_REPO:-https://github.com/adman234/dune-weaver.git}"

    say()  { echo -e "\033[0;34m==>\033[0m $*"; }
    warn() { echo -e "\033[1;33mWARNING:\033[0m $*"; }
    die()  { echo -e "\033[0;31mERROR:\033[0m $*" >&2; exit 1; }

    [[ $EUID -ne 0 ]] || die "Run this as your normal user (e.g. pi), not root or sudo."

    # --- Find the install -------------------------------------------------
    local dir="${DW_DIR:-}"
    if [[ -z "$dir" ]]; then
        for d in "$HOME/dune-weaver" /home/pi/dune-weaver; do
            [[ -f "$d/main.py" ]] && { dir="$d"; break; }
        done
    fi
    [[ -n "$dir" && -f "$dir/main.py" ]] || die "No Dune Weaver install found (looked in ~/dune-weaver and /home/pi/dune-weaver).
       Set DW_DIR=/path/to/dune-weaver, or do a fresh install with scripts/fork-install.sh."
    cd "$dir"
    say "Found install at $dir"

    # Updates run from the web UI run as root and can leave root-owned files.
    say "Fixing file ownership (needs sudo)..."
    sudo chown -R "$(id -un):$(id -gn)" "$dir"

    local is_git=0
    if [[ -d .git ]]; then
        is_git=1
        git config --global --get-all safe.directory 2>/dev/null | grep -qxF "$dir" \
            || git config --global --add safe.directory "$dir"
    fi

    # --- Backup -----------------------------------------------------------
    local ts backup
    ts=$(date +%Y%m%d-%H%M%S)
    backup="$HOME/dw-backups/$ts"
    mkdir -p "$backup"
    say "Backing up to $backup ..."

    # Plain copies of the files you're most likely to want back.
    for f in settings.json state.json playlists.json execution_times.jsonl .env; do
        [[ -f "$f" ]] && cp -p "$f" "$backup/"
    done

    # Everything that isn't part of the code: uploaded patterns, custom logo,
    # touch-app settings, caches, etc. Skips the venv and regenerable caches.
    local excludes=(--exclude=./.venv --exclude=./.git --exclude='*/node_modules'
                    --exclude='*/__pycache__' --exclude=./patterns/cached_svg
                    --exclude=./patterns/cached_images)
    if (( is_git )); then
        git ls-files -z --others \
            | grep -zvE '^(\.venv/|patterns/cached_svg/|patterns/cached_images/)|(^|/)(node_modules|__pycache__)/' \
            | tar --null -T - -czf "$backup/user-data.tar.gz" 2>/dev/null || true
        {
            echo "date:    $(date)"
            echo "dir:     $dir"
            echo "branch:  $(git rev-parse --abbrev-ref HEAD)"
            echo "commit:  $(git rev-parse HEAD)"
            echo "version: $(cat VERSION 2>/dev/null || echo unknown)"
            echo "remotes:"; git remote -v
        } > "$backup/git-info.txt"
        # Any hand edits to tracked files (they'd otherwise be overwritten).
        git diff --binary HEAD > "$backup/local-changes.patch"
        [[ -s "$backup/local-changes.patch" ]] || rm -f "$backup/local-changes.patch"
    else
        tar -czf "$backup/user-data.tar.gz" "${excludes[@]}" . 2>/dev/null || true
    fi

    # System config for reference (regenerated by the update).
    for f in /etc/systemd/system/dune-weaver.service /etc/nginx/sites-available/dune-weaver.conf; do
        [[ -f "$f" ]] && sudo cp "$f" "$backup/" && sudo chown "$(id -un)" "$backup/$(basename "$f")"
    done

    local old_commit old_remote
    old_commit=$( (( is_git )) && git rev-parse HEAD || echo "n/a")
    old_remote=$( (( is_git )) && git remote get-url origin 2>/dev/null || echo "n/a")
    cat > "$backup/RESTORE.txt" <<EOF
Restore user data (settings, playlists, uploaded patterns, logo):
  dw stop
  cp $backup/settings.json $backup/state.json $backup/playlists.json $dir/ 2>/dev/null
  tar -xzf $backup/user-data.tar.gz -C $dir
  dw start

Roll the code back to exactly what was installed before:
  cd $dir
  git remote set-url origin $old_remote
  git fetch origin
  git checkout -f $old_commit
  dw update      # (or: git checkout -B main $old_commit, then dw restart)

Re-apply hand edits you had made (only if local-changes.patch exists):
  cd $dir && git apply $backup/local-changes.patch
EOF
    say "Backup done: $(du -sh "$backup" | cut -f1) in $backup"

    if [[ "${DW_BACKUP_ONLY:-0}" == "1" ]]; then
        say "DW_BACKUP_ONLY=1 set; stopping here."
        return 0
    fi

    (( is_git )) || die "$dir isn't a git checkout, so it can't be switched in place.
       Your data is backed up. Move the old folder aside and do a fresh install:
         mv $dir ${dir}.old-$ts
         curl -fsSL https://raw.githubusercontent.com/adman234/dune-weaver/main/scripts/fork-install.sh | bash
       Then restore with: tar -xzf $backup/user-data.tar.gz -C $dir && dw restart"

    # --- Switch to the fork ---------------------------------------------
    local current branch
    current=$(git rev-parse --abbrev-ref HEAD)
    if [[ -n "${DW_BRANCH:-}" ]]; then
        branch="$DW_BRANCH"
    elif git ls-remote --exit-code --heads "$repo" "$current" >/dev/null 2>&1; then
        branch="$current"
    else
        branch="main"
        [[ "$current" == "main" ]] || warn "Branch '$current' doesn't exist on the fork; switching to main."
    fi

    say "Pointing origin at $repo"
    git remote set-url origin "$repo"
    # Track all branches (installer clones are single-branch, which breaks dw checkout).
    git config --replace-all remote.origin.fetch '+refs/heads/*:refs/remotes/origin/*'
    git fetch origin --prune --tags --force

    git rev-parse --verify --quiet "origin/$branch" >/dev/null || die "Branch '$branch' not found on $repo."

    [[ -f "$backup/local-changes.patch" ]] && warn "You had local edits to tracked files; they're saved in $backup/local-changes.patch and will be overwritten."

    say "Checking out $branch"
    git checkout -f -B "$branch" "origin/$branch"
    git branch --set-upstream-to="origin/$branch" "$branch" >/dev/null

    # --- Run the normal updater from the new code -----------------------
    say "Installing the fork's dw CLI and running dw update..."
    sudo cp "$dir/dw" /usr/local/bin/dw
    sudo chmod +x /usr/local/bin/dw
    dw update

    echo
    say "Done. Now on $(git -C "$dir" rev-parse --abbrev-ref HEAD) @ $(git -C "$dir" rev-parse --short HEAD), version $(cat "$dir/VERSION")."
    say "Backup: $backup  (see RESTORE.txt there)"
}

main "$@"
